import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const repository = fileURLToPath(new URL("../", import.meta.url));
const nx = join(repository, "node_modules/nx/dist/bin/nx.js");

test("formatting defaults to every application Go module and the lint tooling", async (t) => {
  const { root, task } = await fixture(t);
  const directories = [
    "deploy/aio",
    "sdk/nx-cache-proxy",
    "tools/golangci-lint",
  ];
  for (const directory of directories) {
    await mkdir(join(root, directory), { recursive: true });
    await writeFile(
      join(root, directory, "go.mod"),
      `module example.com/${directory}\n\ngo 1.26.0\n`,
    );
    await writeFile(
      join(root, directory, "main.go"),
      "package example\nfunc Example() int {return 1}\n",
    );
  }
  await task("fmt:go", null);
  for (const directory of directories) {
    assert.match(
      await readFile(join(root, directory, "main.go"), "utf8"),
      /func Example\(\) int \{ return 1 \}/,
    );
  }
  assert.equal(
    (await readFile(join(root, "server/main.go"), "utf8")).includes('"os"'),
    false,
  );
});

test("formatting fixes imports, preserves excluded files, and always runs", async (t) => {
  const { root, task, source } = await fixture(t);
  const generated =
    "// Code generated by workflow tests. DO NOT EDIT.\npackage lintfixture\nfunc Generated() int {return 1}\n";
  const testdata = "package example\nfunc Example() int {return 1}\n";
  await writeFile(join(root, "server/generated.go"), generated);
  await mkdir(join(root, "server/testdata"));
  await writeFile(join(root, "server/testdata/example.go"), testdata);
  await mkdir(join(root, "deploy/aio"), { recursive: true });
  await writeFile(join(root, "deploy/aio/main.go"), source);

  await task("fmt:go");
  const formatted = await readFile(join(root, "server/main.go"), "utf8");
  assert.match(formatted, /\/\/ Keep this comment\./);
  assert.match(formatted, /"strings"/);
  assert.match(
    formatted,
    /"strings"\n\n\t"github.com\/stolostron\/ocm-fleet\/lintfixture\/helper"/,
  );
  assert.equal(formatted.includes('"os"'), false);
  assert.match(
    formatted,
    /func Clean\(value string\) string \{ return helper.Lower\(strings.TrimSpace\(value\)\) \}/,
  );
  assert.equal(
    await readFile(join(root, "server/generated.go"), "utf8"),
    generated,
  );
  assert.equal(
    await readFile(join(root, "server/testdata/example.go"), "utf8"),
    testdata,
  );
  assert.equal(
    await readFile(join(root, "deploy/aio/main.go"), "utf8"),
    source,
  );

  await task("fmt:go");
  assert.equal(await readFile(join(root, "server/main.go"), "utf8"), formatted);
  // Reusing identical dirty inputs must still apply edits, not replay a cache hit.
  await writeFile(join(root, "server/main.go"), source);
  await task("fmt:go");
  assert.equal(await readFile(join(root, "server/main.go"), "utf8"), formatted);
});

test("verification formats before real lint and tests, then reuses checks for the resulting source", async (t) => {
  const { root, task, source } = await fixture(t);
  await task("verify:go");
  const formatted = await readFile(join(root, "server/main.go"), "utf8");
  assert.equal(await readFile(join(root, "tested"), "utf8"), "passed");
  await writeFile(join(root, "server/main.go"), source);
  const { stdout } = await task("verify:go");
  assert.equal(await readFile(join(root, "server/main.go"), "utf8"), formatted);
  assert.match(stdout, /local cache|read .* from the cache/);
});

test("verification reports semantic findings without applying linter fixes, and still runs tests", async (t) => {
  const { root, task } = await fixture(t);
  await writeFile(join(root, "server/main.go"), fixableSource);
  await assert.rejects(task("verify:go"), (error) => {
    assert.match(error.stdout + error.stderr, /S1002/);
    return true;
  });
  assert.match(
    await readFile(join(root, "server/main.go"), "utf8"),
    /value == true/,
  );
  assert.equal(await readFile(join(root, "tested"), "utf8"), "passed");
});

test("explicit fixes apply supported linter edits and verify the resulting code", async (t) => {
  const { root, task } = await fixture(t);
  await writeFile(join(root, "server/main.go"), fixableSource);
  await task("fix:go");
  const fixed = await readFile(join(root, "server/main.go"), "utf8");
  assert.equal(fixed.includes("value == true"), false);
  assert.equal(await readFile(join(root, "tested"), "utf8"), "passed");
  await task("fix:go");
  assert.equal(await readFile(join(root, "server/main.go"), "utf8"), fixed);
});

test("fixes still run verification when unfixable findings remain", async (t) => {
  const { root, task } = await fixture(t);
  await writeFile(
    join(root, "server/main.go"),
    fixableSource + '\nfunc Unchecked() { os.Chdir(".") }\n',
  );
  await assert.rejects(task("fix:go"), (error) => {
    assert.match(error.stdout + error.stderr, /errcheck/);
    return true;
  });
  assert.equal(
    (await readFile(join(root, "server/main.go"), "utf8")).includes(
      "value == true",
    ),
    false,
  );
  assert.equal(await readFile(join(root, "tested"), "utf8"), "passed");
});

test("verification propagates test failures after successful formatting and lint", async (t) => {
  const { root, task } = await fixture(t);
  const path = join(root, "server/main_test.go");
  await writeFile(
    path,
    (await readFile(path, "utf8")).replace(
      'Clean(" x ") != "x"',
      'Clean(" x ") != "wrong"',
    ),
  );
  await assert.rejects(task("verify:go"), (error) => {
    assert.match(error.stdout + error.stderr, /unexpected result/);
    return true;
  });
});

test("unknown projects fail before editing any selected source", async (t) => {
  const { root, task, source } = await fixture(t);
  await assert.rejects(task("fmt:go", "server,typo"), (error) => {
    assert.match(error.stdout + error.stderr, /Unknown Go project.*typo/);
    return true;
  });
  assert.equal(await readFile(join(root, "server/main.go"), "utf8"), source);
});

// Use the real Nx runner, compiled linter, and Go tests in disposable workspaces.
// Their separate source trees also exercise Nx caching after source rewrites.
async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), "ocm-fleet-go-workflow-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  for (const directory of ["tools", "server", "bin/tools"]) {
    await mkdir(join(root, directory), { recursive: true });
  }
  await symlink(
    join(repository, "node_modules"),
    join(root, "node_modules"),
    "dir",
  );
  await symlink(
    join(repository, "bin/tools/golangci-lint"),
    join(root, "bin/tools/golangci-lint"),
  );
  await cp(
    join(repository, "tools/go-workflow.mjs"),
    join(root, "tools/go-workflow.mjs"),
  );
  await cp(join(repository, ".golangci.yaml"), join(root, ".golangci.yaml"));
  await writeJSON(join(root, "nx.json"), { cacheDirectory: ".nx/cache" });
  await writeJSON(join(root, "package.json"), {
    name: "go-workflow-fixture",
    private: true,
  });
  await writeFile(
    join(root, ".gitignore"),
    "node_modules/\n.nx/\nbin/\ntested\n",
  );
  const project = JSON.parse(
    await readFile(join(repository, "project.json"), "utf8"),
  );
  const targets = Object.fromEntries(
    ["fmt:go", "verify:go", "fix:go"].map((name) => [
      name,
      project.targets[name],
    ]),
  );
  targets["lint:go:config"] = {
    executor: "nx:run-commands",
    options: {
      command: "bin/tools/golangci-lint config verify --config .golangci.yaml",
    },
    cache: false,
  };
  await writeJSON(join(root, "project.json"), {
    name: "ocm-fleet",
    root: ".",
    targets,
  });
  await writeJSON(join(root, "server/project.json"), {
    name: "server",
    root: "server",
    targets: {
      lint: {
        executor: "nx:run-commands",
        options: {
          command:
            "../bin/tools/golangci-lint run --config ../.golangci.yaml --allow-serial-runners ./...",
          cwd: "server",
          env: { GOWORK: "off" },
        },
        cache: true,
        inputs: [
          "{projectRoot}/**/*.go",
          "{projectRoot}/go.mod",
          "{workspaceRoot}/.golangci.yaml",
        ],
      },
      test: {
        executor: "nx:run-commands",
        options: {
          command: "go test -count=1 ./...",
          cwd: "server",
          env: { GOWORK: "off" },
        },
        cache: true,
        inputs: ["{projectRoot}/**/*.go", "{projectRoot}/go.mod"],
      },
    },
  });
  await writeFile(
    join(root, "server/go.mod"),
    "module github.com/stolostron/ocm-fleet/lintfixture\n\ngo 1.26.0\n",
  );
  await mkdir(join(root, "server/helper"));
  await writeFile(
    join(root, "server/helper/helper.go"),
    'package helper\n\nimport "strings"\n\nfunc Lower(value string) string { return strings.ToLower(value) }\n',
  );
  const source =
    'package lintfixture\n\n// Keep this comment.\nimport ("os"; "github.com/stolostron/ocm-fleet/lintfixture/helper"; "strings")\n\nfunc Clean(value string) string {return helper.Lower(strings.TrimSpace(value))}\n';
  await writeFile(join(root, "server/main.go"), source);
  await writeFile(
    join(root, "server/main_test.go"),
    `package lintfixture

import (
    "bytes"
    "go/format"
    "os"
    "testing"
)

func TestClean(t *testing.T) {
    if Clean(" x ") != "x" { t.Fatal("unexpected result") }
    source, err := os.ReadFile("main.go")
    if err != nil { t.Fatal(err) }
    formatted, err := format.Source(source)
    if err != nil { t.Fatal(err) }
    if !bytes.Equal(source, formatted) { t.Fatal("tests ran before formatting") }
    if err := os.WriteFile("../tested", []byte("passed"), 0600); err != nil { t.Fatal(err) }
}
`,
  );
  return {
    root,
    source,
    task: (target, projects = "server") =>
      run(
        process.execPath,
        [
          nx,
          "run",
          `ocm-fleet:${target}`,
          ...(projects === null ? [] : [`--projects=${projects}`]),
          "--outputStyle=static",
        ],
        {
          cwd: root,
          env: {
            ...process.env,
            NX_DAEMON: "false",
            NX_ISOLATE_PLUGINS: "false",
            NX_NO_CLOUD: "true",
            GOWORK: "off",
          },
          maxBuffer: 4 * 1024 * 1024,
        },
      ),
  };
}

async function writeJSON(path, value) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, JSON.stringify(value));
}

const fixableSource = `package lintfixture

import (
    "os"
    "strings"
)

func Clean(value string) string {return strings.TrimSpace(value)}

func Label(value bool) string {
    if value == true {return "yes"}
    return "no"
}
`;
