test("formatting fixes imports, preserves excluded files, and always runs", async (t) => {
  const { root, task, source } = await fixture(t);
  const generated =
    "// Code generated by quality task tests. DO NOT EDIT.\npackage lintfixture\nfunc Generated() int {return 1}\n";
  const testdata = "package example\nfunc Example() int {return 1}\n";
  await writeFile(join(root, "server/generated.go"), generated);
  await mkdir(join(root, "server/testdata"));
  await writeFile(join(root, "server/testdata/example.go"), testdata);
  await writeFile(join(root, "deploy/aio/main.go"), source);

  await task("fmt");
  const formatted = await readFile(join(root, "server/main.go"), "utf8");
  assert.match(formatted, /\/\/ Keep this comment\./);
  assert.match(formatted, /"strings"/);
  assert.match(
    formatted,
    /"strings"\n\n\t"github.com\/stolostron\/ocm-fleet\/lintfixture\/helper"/,
  );
  assert.equal(formatted.includes('"os"'), false);
  assert.match(
    formatted,
    /func Clean\(value string\) string \{ return helper.Lower\(strings.TrimSpace\(value\)\) \}/,
  );
  assert.equal(
    await readFile(join(root, "server/generated.go"), "utf8"),
    generated,
  );
  assert.equal(
    await readFile(join(root, "server/testdata/example.go"), "utf8"),
    testdata,
  );
  assert.equal(
    await readFile(join(root, "deploy/aio/main.go"), "utf8"),
    source,
  );

  await task("fmt");
  assert.equal(await readFile(join(root, "server/main.go"), "utf8"), formatted);
  // Reusing identical dirty inputs must still apply edits, not replay a cache hit.
  await writeFile(join(root, "server/main.go"), source);
  await task("fmt");
  assert.equal(await readFile(join(root, "server/main.go"), "utf8"), formatted);
});

test("verification formats before real lint and tests, then reuses checks for the resulting source", async (t) => {
  const { root, task, source } = await fixture(t);
  await task("verify");
  const formatted = await readFile(join(root, "server/main.go"), "utf8");
  assert.equal(await readFile(join(root, "tested"), "utf8"), "passed");
  await task("check");
  // Observe actual test executions; Nx's nested console output does not always
  // label a cache hit when its output files are already present.
  assert.equal(await readFile(join(root, "tested"), "utf8"), "passed");
  await writeFile(join(root, "server/main.go"), source);
  await task("verify");
  assert.equal(await readFile(join(root, "server/main.go"), "utf8"), formatted);
  assert.equal(await readFile(join(root, "tested"), "utf8"), "passed");
});

test("server test caching covers embedded assets, fixtures, dependencies, and execution settings", async (t) => {
  const { root, task } = await fixture(t, { serverTestPolicy: true });
  await mkdir(join(root, "server/testdata"));
  await writeJSON(join(root, "proto/project.json"), {
    name: "proto",
    root: "proto",
    targets: {},
  });
  const assets = [
    ["server/schema.sql", "SELECT 1;\n"],
    ["server/resource.proto", 'syntax = "proto3";\n'],
    ["server/testdata/sample.json", "{}\n"],
    ["proto/example.proto", 'syntax = "proto3";\n'],
  ];
  for (const [path, content] of assets)
    await writeFile(join(root, path), content);
  await writeFile(
    join(root, "server/main.go"),
    `package lintfixture

import _ "embed"

//go:embed schema.sql
var schema string

//go:embed resource.proto
var resource string
`,
  );
  await writeFile(
    join(root, "server/main_test.go"),
    `package lintfixture

import (
    "os"
    "testing"
)

func TestCacheInputs(t *testing.T) {
    if schema == "" || resource == "" { t.Fatal("missing embedded assets") }
    for _, path := range []string{"testdata/sample.json", "../proto/example.proto"} {
        if _, err := os.ReadFile(path); err != nil { t.Fatal(err) }
    }
    marker, err := os.OpenFile("../tested", os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0600)
    if err != nil { t.Fatal(err) }
    if _, err := marker.WriteString("passed"); err != nil { t.Fatal(err) }
    if err := marker.Close(); err != nil { t.Fatal(err) }
}
`,
  );
  let executions = 0;
  let env = {
    GOFLAGS: "",
    TESTCONTAINERS_PROVIDER: "docker",
    OCM_RM_QUERY_BENCH: "",
    OCM_RM_INVENTORY_BENCH: "",
  };
  const runTest = async ({ rerun = true, args = [] } = {}) => {
    await task("test", "server", { env, args });
    if (rerun) executions++;
    assert.equal(
      await readFile(join(root, "tested"), "utf8"),
      "passed".repeat(executions),
    );
  };
  await runTest();
  await runTest({ rerun: false });
  for (const [path, content] of [
    ...assets,
    ["server/main.go", await readFile(join(root, "server/main.go"), "utf8")],
  ]) {
    await writeFile(join(root, path), content + "\n");
    await task("refresh:inputs");
    await runTest();
  }
  for (const change of [
    { TESTCONTAINERS_PROVIDER: "podman" },
    { GOFLAGS: "-v" },
    { OCM_RM_QUERY_BENCH: "1" },
    { OCM_RM_INVENTORY_BENCH: "1" },
  ]) {
    env = { ...env, ...change };
    await runTest();
  }
  await runTest({ rerun: false });
  await runTest({ args: ["--skip-nx-cache"] });
});

