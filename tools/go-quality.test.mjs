// Use the real Nx runner, compiled linter, and Go tests in disposable workspaces.
// Their separate source trees also exercise Nx caching after source rewrites.
async function fixture(t, { serverTestPolicy = false } = {}) {
  const root = await mkdtemp(join(tmpdir(), "ocm-fleet-go-quality-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  for (const directory of ["tools", "server", "bin/tools"]) {
    await mkdir(join(root, directory), { recursive: true });
  }
  await symlink(
    join(repository, "node_modules"),
    join(root, "node_modules"),
    "dir",
  );
  for (const name of ["golangci-lint", "goimports", "format-go"]) {
    await symlink(
      join(repository, "bin/tools", name),
      join(root, "bin/tools", name),
    );
  }
  await cp(join(repository, ".golangci.yaml"), join(root, ".golangci.yaml"));
  const { targetDefaults, namedInputs } = JSON.parse(
    await readFile(join(repository, "nx.json"), "utf8"),
  );
  await writeJSON(join(root, "nx.json"), {
    cacheDirectory: ".nx/cache",
    targetDefaults,
    namedInputs: {
      goSource: ["{projectRoot}/**/*"],
      goLintConfig: ["{workspaceRoot}/.golangci.yaml"],
      goRuntime: namedInputs.goRuntime,
      uiSource: ["{projectRoot}/**/*.js"],
      eslintConfig: [],
    },
  });
  await writeJSON(join(root, "package.json"), {
    name: "go-quality-fixture",
    private: true,
  });
  await writeFile(
    join(root, ".gitignore"),
    "node_modules/\n.nx/\nbin/\ntested\nextra-tested\nquality-results/\n",
  );
  const project = JSON.parse(
    await readFile(join(repository, "project.json"), "utf8"),
  );
  const targets = Object.fromEntries(
    ["fmt:go", "verify:go", "fix:go", "lint:go"].map((name) => [
      name,
      project.targets[name],
    ]),
  );
  targets["lint:go:config"] = {
    executor: "nx:run-commands",
    options: {
      command: "bin/tools/golangci-lint config verify --config .golangci.yaml",
    },
    cache: false,
  };
  await writeJSON(join(root, "project.json"), {
    name: "ocm-fleet",
    root: ".",
    targets,
  });
  for (const { directory } of goModules) {
    const project = JSON.parse(
      await readFile(join(repository, directory, "project.json"), "utf8"),
    );
    const testPolicy = project.targets.test;
    // Exercise the production task definitions with real, small Go modules.
    // Most fixtures need neither the server's proto dependency nor the tooling's
    // own test suites; their normal tests run the Go code below instead. The
    // server cache-policy fixture retains proto to exercise dependency inputs.
    delete project.implicitDependencies;
    project.targets = Object.fromEntries(
      [
        "fmt",
        "verify",
        "fix",
        "fix:lint",
        "refresh:inputs",
        "check",
        "lint",
      ].map((name) => [name, project.targets[name]]),
    );
    project.targets.lint.inputs = [
      "{projectRoot}/**/*.go",
      "{projectRoot}/go.mod",
      "{workspaceRoot}/.golangci.yaml",
    ];
    project.targets.test = {
      executor: "nx:run-commands",
      options: {
        command: "go test -count=1 ./...",
        cwd: directory,
        env: { GOWORK: "off" },
      },
      cache: true,
      inputs: ["{projectRoot}/**/*.go", "{projectRoot}/go.mod"],
    };
    if (serverTestPolicy && project.name === "server") {
      // Keep the production cache policy; only replace its Go module and test
      // command with a small real suite that records actual executions on disk.
      project.implicitDependencies = ["proto"];
      project.targets.test.cache = testPolicy.cache;
      project.targets.test.inputs = testPolicy.inputs;
      project.targets.test.outputs = testPolicy.outputs;
    }
    await writeJSON(join(root, directory, "project.json"), project);
    await writeFile(
      join(root, directory, "go.mod"),
      `module example.com/${directory}\n\ngo 1.26.0\n`,
    );
    await writeFile(
      join(root, directory, "main.go"),
      "package example\nfunc Example() int {return 1}\n",
    );
  }
  await writeFile(
    join(root, "server/go.mod"),
    "module github.com/stolostron/ocm-fleet/lintfixture\n\ngo 1.26.0\n",
  );
  await mkdir(join(root, "server/helper"));
  await writeFile(
    join(root, "server/helper/helper.go"),
    'package helper\n\nimport "strings"\n\nfunc Lower(value string) string { return strings.ToLower(value) }\n',
  );
  const source =
    'package lintfixture\n\n// Keep this comment.\nimport ("os"; "github.com/stolostron/ocm-fleet/lintfixture/helper"; "strings")\n\nfunc Clean(value string) string {return helper.Lower(strings.TrimSpace(value))}\n';
  await writeFile(join(root, "server/main.go"), source);
  await writeFile(
    join(root, "server/main_test.go"),
    `package lintfixture

import (
    "bytes"
    "go/format"
    "os"
    "testing"
)

func TestClean(t *testing.T) {
    if Clean(" x ") != "x" { t.Fatal("unexpected result") }
    source, err := os.ReadFile("main.go")
    if err != nil { t.Fatal(err) }
    formatted, err := format.Source(source)
    if err != nil { t.Fatal(err) }
    if !bytes.Equal(source, formatted) { t.Fatal("tests ran before formatting") }
    marker, err := os.OpenFile("../tested", os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0600)
    if err != nil { t.Fatal(err) }
    if _, err := marker.WriteString("passed"); err != nil { t.Fatal(err) }
    if err := marker.Close(); err != nil { t.Fatal(err) }
}
`,
  );
  const runNx = (args, env = {}) =>
    run(process.execPath, [nx, ...args], {
      cwd: root,
      env: {
        ...process.env,
        NX_DAEMON: "false",
        NX_ISOLATE_PLUGINS: "false",
        NX_NO_CLOUD: "true",
        NX_DEFAULT_OUTPUT_STYLE: "static",
        // An uncached outer test run must still exercise this fixture's cache.
        NX_SKIP_NX_CACHE: "false",
        NX_DISABLE_NX_CACHE: "false",
        GOWORK: "off",
        ...env,
      },
      maxBuffer: 4 * 1024 * 1024,
    });
  return {
    root,
    source,
    task: (target, project = "server", { env, args = [] } = {}) =>
      runNx(
        ["run", `${project}:${target}`, "--outputStyle=static", ...args],
        env,
      ),
    configuredGraph: async (target) => {
      const path = join(root, ".nx", "configured-task-graph.json");
      await mkdir(dirname(path), { recursive: true });
      await run(
        "sh",
        [
          "-c",
          project.targets[target].options.command + ' --graph="$1"',
          "graph",
          path,
        ],
        {
          cwd: root,
          env: {
            ...process.env,
            NX_DAEMON: "false",
            NX_ISOLATE_PLUGINS: "false",
            NX_NO_CLOUD: "true",
            GOWORK: "off",
          },
        },
      );
      return JSON.parse(await readFile(path, "utf8")).tasks;
    },
  };
}

// Each real Go test reads all modules from disk before recording its own
// success. Markers stay outside project inputs so they cannot change cache keys.
async function writeWorkspaceChecks(root) {
  await mkdir(join(root, "quality-results"));
  const paths = goModules
    .map(({ directory }) => JSON.stringify(join(root, directory, "main.go")))
    .join(",\n");
  for (const { name, directory } of goModules) {
    await writeFile(
      join(root, directory, "quality_test.go"),
      `package ${name === "server" ? "lintfixture" : "example"}

import (
	"bytes"
	"go/format"
	"os"
	"testing"
)

func TestWorkspaceSourcesAreFormatted(t *testing.T) {
	for _, path := range []string{
${paths},
	} {
		source, err := os.ReadFile(path)
		if err != nil { t.Fatal(err) }
		formatted, err := format.Source(source)
		if err != nil { t.Fatal(err) }
		if !bytes.Equal(source, formatted) { t.Fatalf("%s still needs formatting", path) }
	}
	if err := os.WriteFile(${JSON.stringify(join(root, "quality-results", name))}, []byte("passed"), 0600); err != nil { t.Fatal(err) }
}
`,
    );
  }
}

async function assertWorkspaceChecksPassed(root) {
  for (const { name } of goModules) {
    assert.equal(
      await readFile(join(root, "quality-results", name), "utf8"),
      "passed",
      `${name}'s Go test must observe every module formatted`,
    );
  }
}

async function writeJSON(path, value) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, JSON.stringify(value));
}

