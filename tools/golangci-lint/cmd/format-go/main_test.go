package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/golangci/golangci-lint/v2/pkg/config"
)

func TestFormatFiles(t *testing.T) {
	root := t.TempDir()
	cfg := config.NewDefault()
	cfg.SetConfigDir(root)
	cfg.Run.RelativePathMode = "cfg"
	cfg.Formatters.Enable = []string{"gofmt"}
	cfg.Formatters.Settings.GoFmt.Simplify = true
	cfg.Formatters.Exclusions.Generated = "strict"
	cfg.Formatters.Exclusions.Paths = []string{`excluded/`}
	source := "package example\nfunc Slice(s []int) []int {return s[0:len(s)]}\n"
	files := map[string]string{
		"ordinary file.go":    source,
		"generated.go":        "// Code generated by test. DO NOT EDIT.\n" + source,
		"testdata/example.go": source,
		"vendor/example.go":   source,
		".hidden/example.go":  source,
		"excluded/example.go": source,
	}
	for name, content := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o640); err != nil {
			t.Fatal(err)
		}
	}
	if err := formatFiles(cfg, []string{root}, ""); err != nil {
		t.Fatal(err)
	}
	for name, original := range files {
		path := filepath.Join(root, name)
		content, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if name == "ordinary file.go" {
			if !strings.Contains(string(content), "{ return s[0:] }") {
				t.Fatalf("simplification missing: %s", content)
			}
			info, err := os.Stat(path)
			if err != nil {
				t.Fatal(err)
			}
			if info.Mode().Perm() != 0o640 {
				t.Fatalf("permissions changed: %v", info.Mode())
			}
		} else if string(content) != original {
			t.Errorf("excluded file %s changed", name)
		}
	}
	if err := formatFiles(cfg, []string{root}, ""); err != nil {
		t.Fatal(err)
	}
}

func TestParseFailureIsAnError(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "invalid.go")
	const source = "package example\nfunc invalid(\n"
	if err := os.WriteFile(path, []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
	cfg := config.NewDefault()
	cfg.Run.RelativePathMode = "wd"
	cfg.Formatters.Enable = []string{"gofmt"}
	if err := formatFiles(cfg, []string{root}, ""); err == nil {
		t.Fatal("invalid Go must fail")
	}
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(content) != source {
		t.Fatal("invalid source was overwritten")
	}
}
