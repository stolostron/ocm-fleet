import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { createProjectGraphAsync, workspaceRoot } from "@nx/devkit";

export function formatProjects(nodes) {
  return Object.keys(nodes)
    .sort()
    .map((name) => {
      const { root, metadata = {} } = nodes[name].data;
      const instruction = metadata.additionalAgentInstruction ?? "";
      const instructions = Array.isArray(instruction)
        ? instruction.join(", ")
        : instruction;
      return `- ${name} (${root}) - ${metadata.description ?? ""} ${instructions}`.trimEnd();
    })
    .join("\n");
}

export function updateAgents(contents, nodes) {
  const headings = [
    ...contents.matchAll(/^## Nx Projects \(autogenerated\)[ \t]*(?=\r?$)/gm),
  ];
  if (headings.length !== 1) {
    throw new Error(
      "AGENTS.md must contain exactly one Nx Projects (autogenerated) section",
    );
  }

  const heading = headings[0];
  const bodyStart = heading.index + heading[0].length;
  const nextHeading = /^#{1,2}[ \t]+/m.exec(contents.slice(bodyStart));
  const suffix = nextHeading
    ? contents.slice(bodyStart + nextHeading.index)
    : "";
  const newline = contents.includes("\r\n") ? "\r\n" : "\n";
  const projects = formatProjects(nodes).replaceAll("\n", newline);
  const note = "Regenerate: `npx nx run ocm-fleet:generate-agents`.";
  const body =
    newline + newline + note + (projects ? newline + newline + projects : "");

  return (
    contents.slice(0, bodyStart) +
    body +
    (suffix ? newline + newline + suffix : newline)
  );
}

async function main() {
  const graph = await createProjectGraphAsync();
  const path = resolve(workspaceRoot, "AGENTS.md");
  const original = await readFile(path, "utf8");
  const updated = updateAgents(original, graph.nodes);
  if (updated !== original) {
    await writeFile(path, updated);
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  await main();
}
